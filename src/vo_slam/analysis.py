"""Where the odometry goes wrong: error against rotation speed, and drift against distance.

Two questions, answered from the trajectories in reports/trajectories and the ground truth:

1. Fast rotation: every 1 s window is binned by how far the camera really turned in it;
   the median RPE per bin shows which motions each mode can and cannot follow.
2. Drift: for path segments of 0.5-8 m (as KITTI's t_rel does for 100-800 m), the
   translation error at the end of the segment as a percentage of its length. Odometry
   error should grow with distance; loop closure should cap it.

Monocular trajectories are rescaled by their Sim3 scale first.

Example:
    vo-analyse     # -> reports/error_analysis.{md,json}, reports/figures/error_analysis.png
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from .config import REPORTS_DIR, SEQUENCES, TUM_DIR
from .geometry import invert, rotation_angle
from .metrics import ate, rpe_pairs
from .run import MODES, TRAJ_DIR
from .tum import associate, read_trajectory

SPEED_BINS = (0.0, 10.0, 20.0, 40.0, np.inf)  # ground-truth rotation in a 1 s window (deg)
SEGMENTS_M = (0.5, 1.0, 2.0, 4.0, 8.0)


def matched(gt_t: np.ndarray, gt_p: np.ndarray, est_t: np.ndarray, est_p: np.ndarray,
            monocular: bool) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Time-matched (stamps, gt, est) with monocular translations in metres."""
    pairs = associate(est_t, gt_t)
    ei, gi = [i for i, _ in pairs], [j for _, j in pairs]
    gt, est = gt_p[gi], est_p[ei].copy()
    if monocular:
        est[:, :3, 3] *= ate(gt, est, with_scale=True).scale
    return est_t[ei], gt, est


def window_errors(t: np.ndarray, gt: np.ndarray, est: np.ndarray, delta: float = 1.0
                  ) -> np.ndarray:
    """Rows (gt rotation deg, trans error m, rot error deg) for each `delta`-second window."""
    rows = []
    for i, j in rpe_pairs(t, delta):
        rel_gt = invert(gt[i]) @ gt[j]
        E = invert(rel_gt) @ invert(est[i]) @ est[j]
        rows.append((np.degrees(rotation_angle(rel_gt[:3, :3])), np.linalg.norm(E[:3, 3]),
                     np.degrees(rotation_angle(E[:3, :3]))))
    return np.array(rows).reshape(-1, 3)


def segment_drift(gt: np.ndarray, est: np.ndarray, length: float, step: int = 5
                  ) -> np.ndarray:
    """Translation error (% of length) over path segments of `length` metres of GT motion."""
    d = np.concatenate([[0], np.cumsum(np.linalg.norm(np.diff(gt[:, :3, 3], axis=0), axis=1))])
    out = []
    for i in range(0, len(gt), step):
        j = int(np.searchsorted(d, d[i] + length))
        if j >= len(gt):
            break
        E = invert(invert(gt[i]) @ gt[j]) @ invert(est[i]) @ est[j]
        out.append(100 * np.linalg.norm(E[:3, 3]) / (d[j] - d[i]))
    return np.array(out)


def bin_label(lo: float, hi: float) -> str:
    return f"> {lo:.0f}" if np.isinf(hi) else f"{lo:.0f}–{hi:.0f}"


def analyse(traj_dir: Path, data_dir: Path) -> dict:
    windows: dict[str, list[np.ndarray]] = {}
    drift: dict[str, dict[str, dict[str, float]]] = {}
    for s, info in SEQUENCES.items():
        gt_path = data_dir / info.name / "groundtruth.txt"
        if not gt_path.exists():
            continue
        gt_t, gt_p = read_trajectory(gt_path)
        for mode in MODES:
            path = traj_dir / f"{s}_{mode}.txt"
            if not path.exists():
                continue
            t, gt, est = matched(gt_t, gt_p, *read_trajectory(path), mode == "mono")
            windows.setdefault(mode, []).append(window_errors(t, gt, est))
            for L in SEGMENTS_M:
                e = segment_drift(gt, est, L)
                if len(e):
                    drift.setdefault(s, {}).setdefault(mode, {})[str(L)] = float(np.median(e))
    speed = {}
    for mode, rows in windows.items():
        w = np.vstack(rows)
        for lo, hi in zip(SPEED_BINS[:-1], SPEED_BINS[1:], strict=True):
            sel = w[(w[:, 0] >= lo) & (w[:, 0] < hi)]
            if len(sel):
                speed.setdefault(mode, {})[bin_label(lo, hi)] = {
                    "windows": len(sel), "trans_cm": 100 * float(np.median(sel[:, 1])),
                    "rot_deg": float(np.median(sel[:, 2])),
                    "bad_pct": 100 * float(np.mean((sel[:, 1] > 0.1) | (sel[:, 2] > 5)))}
    return {"by_rotation_speed": speed, "drift_by_segment": drift}


def to_markdown(res: dict) -> str:
    speed, drift = res["by_rotation_speed"], res["drift_by_segment"]
    bins = [bin_label(lo, hi) for lo, hi in zip(SPEED_BINS[:-1], SPEED_BINS[1:], strict=True)]
    lines = ["# Error analysis", "",
             "Generated by `vo-analyse` from `reports/trajectories`. All four sequences pooled.",
             "", "## Error against rotation speed", "",
             "Each 1 s window is binned by how far the camera really rotated in it. Cells: "
             "median translation error (cm) / median rotation error (°) / share of windows that "
             "are badly wrong (> 10 cm or > 5°).", "",
             "| Mode | " + " | ".join(f"{b} °/s" for b in bins) + " |",
             "|---|" + "---|" * len(bins)]
    counts = next(iter(speed.values()))
    for mode, by in speed.items():
        cells = [f"{by[b]['trans_cm']:.1f} / {by[b]['rot_deg']:.2f} / {by[b]['bad_pct']:.0f} %"
                 if b in by else "–" for b in bins]
        lines.append(f"| {mode} | " + " | ".join(cells) + " |")
    lines += ["| windows | " + " | ".join(str(counts.get(b, {}).get("windows", 0))
                                         for b in bins) + " |", "",
              "## Drift against distance travelled", "",
              "Median translation error at the end of a path segment, as % of the segment "
              "length (KITTI-style t_rel on a room scale).", "",
              "| Sequence | Mode | " + " | ".join(f"{L:g} m" for L in SEGMENTS_M) + " |",
              "|---|---|" + "---|" * len(SEGMENTS_M)]
    for s, by_mode in drift.items():
        for mode, by_len in by_mode.items():
            cells = [f"{by_len[str(L)]:.1f}" if str(L) in by_len else "–" for L in SEGMENTS_M]
            lines.append(f"| {s} | {mode} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def plot(res: dict, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    colors = {"rgbd-f2f": "tab:orange", "rgbd-kf": "tab:blue", "rgbd-slam": "tab:green",
              "mono": "tab:red"}
    fig, (a, b) = plt.subplots(1, 2, figsize=(11, 4))
    bins = [bin_label(lo, hi) for lo, hi in zip(SPEED_BINS[:-1], SPEED_BINS[1:], strict=True)]
    x = np.arange(len(bins))
    speed = res["by_rotation_speed"]
    for k, (mode, by) in enumerate(speed.items()):
        vals = [by.get(bn, {}).get("rot_deg", np.nan) for bn in bins]
        a.bar(x + (k - 1.5) * 0.2, vals, 0.2, color=colors[mode], label=mode)
    a.set_xticks(x, [f"{bn} °/s" for bn in bins])
    a.set_yscale("log")
    a.set_ylabel("median rotation error per 1 s window (°)")
    a.set_title("Error grows with rotation speed", fontsize=10)
    a.legend(fontsize=8)
    a.grid(alpha=0.3, axis="y")
    drift = res["drift_by_segment"].get("fr3_long_office_household", {})
    for mode, by_len in drift.items():
        ls = [float(L) for L in by_len]
        b.plot(ls, list(by_len.values()), "o-", color=colors[mode], label=mode)
    b.set_xscale("log")
    b.set_yscale("log")
    b.set_xticks(list(SEGMENTS_M), [f"{L:g}" for L in SEGMENTS_M])
    b.xaxis.set_minor_formatter(plt.NullFormatter())
    b.yaxis.set_major_formatter(plt.ScalarFormatter())
    b.yaxis.set_minor_formatter(plt.NullFormatter())
    b.set_xlabel("path segment length (m)")
    b.set_ylabel("translation error (% of length)")
    b.set_title("fr3_long_office_household: drift over distance", fontsize=10)
    if drift:
        b.legend(fontsize=8)
    b.grid(alpha=0.3, which="both")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=120)
    plt.close(fig)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--traj-dir", type=Path, default=TRAJ_DIR)
    parser.add_argument("--data-dir", type=Path, default=TUM_DIR)
    parser.add_argument("--out", type=Path, default=REPORTS_DIR)
    args = parser.parse_args(argv)
    res = analyse(args.traj_dir, args.data_dir)
    if not res["by_rotation_speed"]:
        raise SystemExit(f"No trajectories in {args.traj_dir}; run vo-run first.")
    (args.out / "error_analysis.json").write_text(json.dumps(res, indent=2) + "\n")
    md = to_markdown(res)
    (args.out / "error_analysis.md").write_text(md)
    plot(res, args.out / "figures" / "error_analysis.png")
    print(md)


if __name__ == "__main__":
    main()
