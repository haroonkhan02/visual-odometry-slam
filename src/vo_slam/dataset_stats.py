"""Summarise the downloaded TUM sequences: frames, ground-truth coverage, motion, depth.

Example:
    vo-check                       # all downloaded sequences -> reports/dataset_stats.*
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from .config import REPORTS_DIR, SEQUENCES, TUM_DIR
from .geometry import path_length, relative, rotation_angle
from .tum import TumSequence


def sequence_stats(seq: TumSequence, depth_samples: int = 30) -> dict:
    idx, gt = seq.ground_truth()
    pos = gt[:, :3, 3]
    dt = np.diff(seq.stamps)
    duration = float(seq.stamps[-1] - seq.stamps[0])
    # Per-frame motion between consecutive GT-matched frames: what the tracker must handle
    step_t = np.linalg.norm(np.diff(pos, axis=0), axis=1)
    step_r = np.degrees([rotation_angle(relative(gt[k], gt[k + 1])[:3, :3])
                         for k in range(len(gt) - 1)])
    picks = np.linspace(0, len(seq) - 1, min(depth_samples, len(seq))).astype(int)
    valid = [float((seq.depth(i) > 0).mean()) for i in picks]
    loop_gap = float(np.linalg.norm(pos[-1] - pos[0]))
    return {
        "frames": len(seq),
        "frames_with_gt": int(len(idx)),
        "duration_s": round(duration, 1),
        "fps": round(float(1 / np.median(dt)), 1),
        "max_frame_gap_s": round(float(dt.max()), 3),
        "path_length_m": round(path_length(pos), 2),
        "total_rotation_deg": round(float(step_r.sum())),
        "mean_speed_m_s": round(path_length(pos) / duration, 3),
        "p95_step_cm": round(float(np.percentile(step_t, 95) * 100), 2),
        "p95_step_deg": round(float(np.percentile(step_r, 95)), 2),
        "start_end_distance_m": round(loop_gap, 2),
        "depth_valid_fraction": round(float(np.mean(valid)), 3),
    }


def plot_trajectories(seqs: dict[str, TumSequence], out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, len(seqs), figsize=(4 * len(seqs), 4), squeeze=False)
    for ax, (name, seq) in zip(axes[0], seqs.items(), strict=True):
        pos = seq.ground_truth()[1][:, :3, 3]
        ax.plot(pos[:, 0], pos[:, 1], lw=1)
        ax.plot(*pos[0, :2], "go", label="start")
        ax.plot(*pos[-1, :2], "rs", label="end")
        ax.set_title(name)
        ax.set_xlabel("x (m)")
        ax.set_ylabel("y (m)")
        ax.set_aspect("equal", adjustable="datalim")
        ax.grid(alpha=0.3)
    axes[0][0].legend(loc="best", fontsize=8)
    fig.suptitle("Ground-truth camera paths, top view (motion-capture frame)")
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=120)
    plt.close(fig)


def to_markdown(stats: dict[str, dict]) -> str:
    cols = [("frames", "Frames"), ("frames_with_gt", "With GT"), ("duration_s", "Duration (s)"),
            ("path_length_m", "Path (m)"), ("total_rotation_deg", "Rotation (°)"),
            ("mean_speed_m_s", "Speed (m/s)"), ("p95_step_cm", "p95 step (cm)"),
            ("p95_step_deg", "p95 step (°)"), ("start_end_distance_m", "Start–end (m)"),
            ("depth_valid_fraction", "Valid depth")]
    lines = ["# TUM RGB-D sequences used", "",
             "Generated by `vo-check`. Frames are RGB images paired with a depth image within "
             "20 ms; *With GT* have a motion-capture pose within 20 ms. Steps are between "
             "consecutive frames. Path and rotation are summed frame to frame, so fast "
             "back-and-forth motion counts fully; the figures on the TUM website average over "
             "about one-second steps and come out lower.", "",
             "| Sequence | " + " | ".join(c for _, c in cols) + " |",
             "|---|" + "---|" * len(cols)]
    for name, s in stats.items():
        lines.append(f"| {name} | " + " | ".join(f"{s[k]:,}" if isinstance(s[k], int)
                                                  else str(s[k]) for k, _ in cols) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data-dir", type=Path, default=TUM_DIR)
    parser.add_argument("--out", type=Path, default=REPORTS_DIR)
    args = parser.parse_args(argv)
    seqs = {short: TumSequence.load(short, args.data_dir) for short, info in SEQUENCES.items()
            if (args.data_dir / info.name / "rgb.txt").exists()}
    if not seqs:
        raise SystemExit(f"No sequences in {args.data_dir}; run vo-download first.")
    stats = {name: sequence_stats(seq) for name, seq in seqs.items()}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "dataset_stats.json").write_text(json.dumps(stats, indent=2) + "\n")
    (args.out / "dataset_stats.md").write_text(to_markdown(stats))
    plot_trajectories(seqs, args.out / "figures" / "gt_trajectories.png")
    print(to_markdown(stats))


if __name__ == "__main__":
    main()
