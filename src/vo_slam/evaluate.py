"""Score the trajectories written by vo-run against motion-capture ground truth.

ATE uses a rigid (SE3) alignment for RGB-D and a similarity (Sim3) alignment for monocular
runs, whose scale is unknown. RPE is over 1 s windows; monocular translations are rescaled
by the Sim3 scale first. Drift is the RPE translation error as a percentage of the distance
travelled in the same window (the KITTI-style t_rel, but over 1 s rather than 100-800 m).

Example:
    vo-eval          # reports/trajectories/*.txt -> reports/vo_results.{md,json} + figures
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from .config import REPORTS_DIR, SEQUENCES, TUM_DIR
from .metrics import ate, rpe, rpe_pairs
from .run import MODES, TRAJ_DIR
from .tum import associate, read_trajectory


def evaluate(gt_stamps: np.ndarray, gt_poses: np.ndarray, est_stamps: np.ndarray,
             est_poses: np.ndarray, monocular: bool, delta: float = 1.0) -> dict:
    """Metrics for one trajectory; estimated frames without GT within 20 ms are not scored."""
    pairs = associate(est_stamps, gt_stamps)
    ei, gi = np.array([i for i, _ in pairs]), np.array([j for _, j in pairs])
    est, gt, t = est_poses[ei], gt_poses[gi], est_stamps[ei]
    a = ate(gt, est, with_scale=monocular)
    r = rpe(gt, est, t, delta, scale=a.scale)
    dist = np.array([np.linalg.norm(gt[j, :3, 3] - gt[i, :3, 3]) for i, j in rpe_pairs(t, delta)])
    moving = dist > 0.05  # windows where the camera moved 5 cm or more
    drift = 100 * float(np.mean(r.trans_errors[moving] / dist[moving]))
    return {
        "frames_scored": len(pairs),
        "ate_rmse_m": a.rmse, "ate_median_m": a.median, "ate_max_m": a.max, "sim3_scale": a.scale,
        "rpe_trans_m_per_s": r.trans_rmse, "rpe_rot_deg_per_s": r.rot_rmse_deg,
        "drift_pct": drift, "gt_path_m": float(np.linalg.norm(np.diff(gt[:, :3, 3], axis=0),
                                                              axis=1).sum()),
        "_aligned": a.aligned, "_gt": gt[:, :3, 3], "_t": t - t[0], "_err": a.errors,
    }


def plot(results: dict[str, dict[str, dict]], out_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    seqs = list(results)
    colors = {"rgbd-f2f": "tab:orange", "rgbd-kf": "tab:blue", "mono": "tab:red"}
    fig, axes = plt.subplots(1, len(seqs), figsize=(4.2 * len(seqs), 4.4), squeeze=False)
    for ax, s in zip(axes[0], seqs, strict=True):
        first = next(iter(results[s].values()))
        ax.plot(first["_gt"][:, 0], first["_gt"][:, 1], "k-", lw=2, alpha=0.35,
                label="ground truth")
        for mode, r in results[s].items():
            ax.plot(r["_aligned"][:, 0], r["_aligned"][:, 1], lw=1, color=colors[mode],
                    label=f"{mode} ({100 * r['ate_rmse_m']:.1f} cm)")
        ax.set_title(s, fontsize=10)
        ax.set_xlabel("x (m)")
        ax.set_aspect("equal", adjustable="datalim")
        ax.grid(alpha=0.3)
        ax.legend(fontsize=7, loc="best")
    axes[0][0].set_ylabel("y (m)")
    fig.suptitle("Estimated vs ground-truth camera path, top view "
                 "(after alignment; ATE in brackets)")
    fig.tight_layout()
    out_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_dir / "trajectories.png", dpi=120)
    plt.close(fig)

    fig, axes = plt.subplots(1, len(seqs), figsize=(4.2 * len(seqs), 3.2), squeeze=False)
    for ax, s in zip(axes[0], seqs, strict=True):
        for mode, r in results[s].items():
            ax.plot(r["_t"], 100 * r["_err"], lw=1, color=colors[mode], label=mode)
        ax.set_title(s, fontsize=10)
        ax.set_xlabel("time (s)")
        ax.grid(alpha=0.3)
    axes[0][0].set_ylabel("position error after alignment (cm)")
    axes[0][0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out_dir / "ate_over_time.png", dpi=120)
    plt.close(fig)


def to_markdown(results: dict[str, dict[str, dict]], runs: dict[str, dict[str, dict]]) -> str:
    lines = [
        "# Visual odometry results on TUM RGB-D", "",
        "Generated by `vo-run` (sequential, one process, Apple M5 CPU) and `vo-eval`. ATE: RMSE "
        "of camera positions after SE3 alignment (RGB-D) or Sim3 alignment (mono, scale "
        "unknown). RPE and drift over 1 s windows; drift = translation error / distance "
        "travelled in that window, windows under 5 cm of motion skipped. *Failed*: frames "
        "with no pose from PnP (RGB-D: constant-velocity guess; mono: copy of the previous "
        "pose). *Lost*: mono re-initialisations. FPS includes reading the PNGs.", "",
        "| Sequence | Mode | ATE RMSE (cm) | ATE max (cm) | RPE (cm/s) | RPE (°/s) | Drift (%) "
        "| Keyframes | Failed | Lost | FPS |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for s, by_mode in results.items():
        for mode, r in by_mode.items():
            st = runs[s][mode]
            lines.append(
                f"| {s} | {mode} | {100 * r['ate_rmse_m']:.1f} | {100 * r['ate_max_m']:.1f} | "
                f"{100 * r['rpe_trans_m_per_s']:.1f} | {r['rpe_rot_deg_per_s']:.2f} | "
                f"{r['drift_pct']:.1f} | {st['keyframes']} | "
                f"{st.get('failures', st.get('failed', 0))} | {st.get('losses', '–')} | "
                f"{st['fps']:.0f} |")
    lines += ["", "Monocular Sim3 scale (estimate units → metres): " + ", ".join(
        f"{s} {r['mono']['sim3_scale']:.2f}" for s, r in results.items() if "mono" in r) + "."]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--traj-dir", type=Path, default=TRAJ_DIR)
    parser.add_argument("--data-dir", type=Path, default=TUM_DIR)
    parser.add_argument("--out", type=Path, default=REPORTS_DIR)
    args = parser.parse_args(argv)
    results: dict[str, dict[str, dict]] = {}
    runs: dict[str, dict[str, dict]] = {}
    for s, info in SEQUENCES.items():
        for mode in MODES:
            path = args.traj_dir / f"{s}_{mode}.txt"
            if not path.exists():
                continue
            gt_t, gt_p = read_trajectory(args.data_dir / info.name / "groundtruth.txt")
            est_t, est_p = read_trajectory(path)
            results.setdefault(s, {})[mode] = evaluate(gt_t, gt_p, est_t, est_p, mode == "mono")
            runs.setdefault(s, {})[mode] = json.loads(path.with_suffix(".json").read_text())
    if not results:
        raise SystemExit(f"No trajectories in {args.traj_dir}; run vo-run first.")
    clean = {s: {m: {k: v for k, v in r.items() if not k.startswith("_")} | runs[s][m]
                 for m, r in by.items()} for s, by in results.items()}
    (args.out / "vo_results.json").write_text(json.dumps(clean, indent=2) + "\n")
    md = to_markdown(results, runs)
    (args.out / "vo_results.md").write_text(md)
    plot(results, args.out / "figures")
    print(md)


if __name__ == "__main__":
    main()
